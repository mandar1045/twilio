defmodule Twilio do
  @moduledoc """
  Elixir SDK for Twilio - Api (API version 1.0.0).

  This is the public Twilio REST API.

  ## Configuration

  The API key is read from `TWILIO_ACCOUNT_SID` and `TWILIO_AUTH_TOKEN`, or set it in your config:

      config :twilio, api_key: {"user", "password"}, max_retries: 3, timeout: 60_000

  `:account_sid` fills `{AccountSid}` in every path, read from `TWILIO_ACCOUNT_SID` unless set: `config :twilio, account_sid: "..."`, or `account_sid: "..."` on a single call.

  Any setting can also be given to a single call, as the last argument:

      Twilio.SomeResource.some_call(params, timeout: 5_000)

  Generated by [Infusion](https://github.com/mandar1045/infusion).
  """

  @defaults [
    base_url: "https://api.twilio.com",
    api_key: {{:env, "TWILIO_ACCOUNT_SID"}, {:env, "TWILIO_AUTH_TOKEN"}},
    auth: :basic,
    user_agent: "twilio/0.1.0 (Elixir; infusion_runtime)",
    account_sid: {:env, "TWILIO_ACCOUNT_SID"}
  ]

  @doc """
  The settings for a call: the defaults, then `config :twilio, ...`, then
  `opts`. See `Infusion.Runtime.Config` for every setting.
  """
  @spec config(keyword) :: Infusion.Runtime.Config.t()
  def config(opts \\ []) do
    Infusion.Runtime.Config.new([@defaults, Application.get_all_env(:twilio), opts])
  end

  @doc """
  Calls an endpoint this SDK has no function for:

      Twilio.request(:get, "/some/path", %{"limit" => 10})

  `params` go into the query for GET and DELETE, into a JSON body otherwise.
  """
  @spec request(atom, String.t(), map | keyword, keyword) ::
          {:ok, term} | {:error, Infusion.Runtime.Error.t()}
  def request(method, path, params \\ %{}, opts \\ []) do
    operation = %{
      id: nil,
      method: method,
      path: path,
      body: if(method in [:get, :head, :delete], do: nil, else: :json)
    }

    __request__(operation, [], params, opts)
  end

  @doc false
  def __request__(operation, path_args, params, opts) do
    Infusion.Runtime.Request.run(config(), operation, path_args, params, opts)
  end

  @doc false
  def __stream__(operation, path_args, params, opts) do
    Infusion.Runtime.Request.stream(config(), operation, path_args, params, opts)
  end

  @doc false
  def __paginate__(operation, path_args, params, opts) do
    Infusion.Runtime.Paginate.stream(config(), operation, path_args, params, opts)
  end
end
